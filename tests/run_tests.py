def write(base, files):
    for rel, content in files.items():
        p = base / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")


def scan(base):
    out = base / "scan.json"
    r = subprocess.run([sys.executable, str(SCRIPTS / "scan.py"), str(base), "--no-audit", "--no-git-history", "--quiet", "--out", str(out)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        FALHAS.append(f"scan.py falhou em {base.name}: {r.stderr[-800:]}")
        return {}
    return json.loads(out.read_text(encoding="utf-8"))


def regras(res, cid=None):
    out = set()
    for group in ("checks", "prontidao"):
        for k, c in (res.get(group) or {}).items():
            if cid and k != cid:
                continue
            for a in c["achados"]:
                out.add(f"{k}:{a['regra']}")
    return out


def esperar(nome, res, esperadas, proibidas=()):
    achou = regras(res)
    for e in esperadas:
        if e not in achou:
            FALHAS.append(f"[{nome}] faltou {e}")
    for p in proibidas:
        if p in achou:
            FALHAS.append(f"[{nome}] não devia achar {p}")
    if res.get("erros_do_scanner"):
        FALHAS.append(f"[{nome}] erros do scanner: {res['erros_do_scanner']}")
    print(f"  {'✔' if not [f for f in FALHAS if f.startswith('[' + nome + ']')] else '✘'} {nome}: {len(achou)} regras disparadas")


